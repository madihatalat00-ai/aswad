#!/usr/bin/env python3
"""Bundle index.html, styles.css, ledger.js and app.js into one file.

The result, house-build-ledger.html, opens with a double-click anywhere
(downloaded to a phone, emailed, opened from a file viewer) because it needs
no neighbouring files. Re-run after changing any of the sources:

    python3 house-tracker/build_standalone.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent


def read(name):
    return (HERE / name).read_text(encoding="utf-8")


def inline_script(code):
    # A literal "</script" inside the code would end the tag early.
    return "<script>\n" + code.replace("</script", "<\\/script") + "</script>"


html = read("index.html")
replacements = {
    '<link rel="stylesheet" href="styles.css" />':
        "<style>\n" + read("styles.css") + "</style>",
    '<script src="ledger.js"></script>': inline_script(read("ledger.js")),
    '<script src="app.js"></script>': inline_script(read("app.js")),
}
for tag, inlined in replacements.items():
    if html.count(tag) != 1:
        raise SystemExit("index.html no longer contains exactly one " + tag)
    html = html.replace(tag, inlined)

# Note goes after the doctype so the page still renders in standards mode.
doctype = "<!DOCTYPE html>\n"
if not html.startswith(doctype):
    raise SystemExit("index.html should start with " + doctype.strip())
note = ("<!-- Generated by build_standalone.py from index.html, styles.css,\n"
        "     ledger.js and app.js. Edit those files, not this one. -->\n")
out = HERE / "house-build-ledger.html"
out.write_text(doctype + note + html[len(doctype):], encoding="utf-8")
print("Wrote", out.relative_to(HERE.parent))
